const cache = new Map();
export function iconPath(name) {
  let p = cache.get(name);
  if (!p) { p = new Path2D(ICONS[name] || ICONS.gold); cache.set(name, p); }
  return p;
}

// 캔버스에 아이콘 (x,y 는 가운데, size 는 한 변 px)
export function drawIcon(ctx, name, x, y, size, color, lw = 1.6) {
  const k = size / 24;
  ctx.save();
  ctx.translate(x - size / 2, y - size / 2);
  ctx.scale(k, k);
  ctx.strokeStyle = color;
  ctx.lineWidth = lw;
  ctx.lineCap = 'round';
  ctx.lineJoin = 'round';
  ctx.stroke(iconPath(name));
  ctx.restore();
}

